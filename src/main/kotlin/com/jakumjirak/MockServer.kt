package com.jakumjirak

import com.intellij.openapi.Disposable
import com.intellij.openapi.components.Service
import com.intellij.openapi.project.Project
import io.ktor.http.ContentType
import io.ktor.http.HttpMethod
import io.ktor.server.application.call
import io.ktor.server.engine.embeddedServer
import io.ktor.server.netty.Netty
import io.ktor.server.netty.NettyApplicationEngine
import io.ktor.server.response.respondText
import io.ktor.server.routing.route
import io.ktor.server.routing.routing
import io.swagger.v3.oas.models.OpenAPI

/**
 * Embedded mock server (Ktor/Netty). Every operation of the OpenAPI document is served
 * with a sample JSON body generated by [OpenApiDataGenerator]; OpenAPI `{param}` path
 * templates map directly onto Ktor route parameters.
 */
class MockServer {
    @Volatile
    private var server: NettyApplicationEngine? = null

    @Volatile
    var port: Int = 0
        private set

    @Synchronized
    fun start(port: Int, openApi: OpenAPI) {
        require(port in VALID_PORTS) { "Port must be between 1 and 65535 (was $port)" }
        stop()
        val dataGenerator = OpenApiDataGenerator(openApi)
        server = embeddedServer(Netty, port = port, host = LOOPBACK) {
            routing {
                openApi.paths?.forEach { (path, pathItem) ->
                    pathItem.readOperationsMap().forEach { (method, operation) ->
                        route(path, HttpMethod.parse(method.name)) {
                            handle {
                                call.respondText(dataGenerator.generateForOperation(operation), ContentType.Application.Json)
                            }
                        }
                    }
                }
            }
        }.start(wait = false)
        this.port = port
    }

    @Synchronized
    fun stop() {
        server?.stop(GRACE_PERIOD_MS, TIMEOUT_MS)
        server = null
        port = 0
    }

    fun isRunning(): Boolean = server != null

    companion object {
        /** The mock server only listens on loopback so it is never exposed to the network. */
        const val LOOPBACK = "127.0.0.1"
        val VALID_PORTS = 1..65_535
        private const val GRACE_PERIOD_MS = 500L
        private const val TIMEOUT_MS = 2_000L
    }
}

/** Owns the project's mock server and shuts it down with the project. */
@Service(Service.Level.PROJECT)
class MockServerService : Disposable {
    val server = MockServer()

    override fun dispose() = server.stop()

    companion object {
        fun getInstance(project: Project): MockServerService = project.getService(MockServerService::class.java)
    }
}
